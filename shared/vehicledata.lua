---Vehicle class for a model name or hash, without needing the vehicle to exist.
---@param model string|number model name or hash
---@return number? class
function RSVehicleData.GetClass(model)
    local entry = RSVehicleData.Find(model)
    return entry and entry.class or nil
end

-- NOTE: price is deliberately absent. The dump carries Price (-1 or 100) and
-- MonetaryValue, but MonetaryValue has only 20 distinct values across 921
-- vehicles -- 153 of them share 35000. Those are handling-file buckets, not
-- dealership prices, and feeding them into a payout valuation would be worse
-- than having no data at all.

---@param model string|number
---@return table? entry
function RSVehicleData.Find(model)
    if type(model) == 'string' then
        return RSVehicleData.Models[model:lower()]
    end

    if type(model) ~= 'number' then return nil end

    -- Hash lookup is built once, on first use. Doing it at load would hash every
    -- model on every resource that includes this file, for callers that may only
    -- ever look up by name.
    if not RSVehicleData._byHash then
        local byHash = {}
        for name, entry in pairs(RSVehicleData.Models) do
            byHash[joaat(name)] = entry
        end
        RSVehicleData._byHash = byHash
    end

    return RSVehicleData._byHash[model]
end
